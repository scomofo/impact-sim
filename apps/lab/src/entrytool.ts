/** Generates the script the atmospheric-entry tool runs. */

export const ENTRY_BODIES = ["earth", "mars", "venus", "titan", "jupiter"] as const;

export interface EntrySpec {
  body: string;
  /** Entry speed, m/s. */
  v0: number;
  /** Flight-path angle, degrees (negative = descending). */
  gammaDeg: number;
  /** Entry interface altitude, km. */
  h0: number;
  mass: number;
  area: number;
  cd: number;
  ld: number;
  bankDeg: number;
  noseRadius: number;
  /** Stop altitude, km. */
  hStop: number;
  /** Stop speed, m/s. */
  vStop: number;
  plot: "hv" | "gt" | "qt" | "hr";
}

